import { staticAssets } from "./cache-policy.ts";

export function securityHeaders() {
  return {
    "X-Content-Type-Options": "nosniff",
    "X-Frame-Options": "DENY",
    "Referrer-Policy": "strict-origin-when-cross-origin",
    "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=()",
    "Strict-Transport-Security": "max-age=63072000; includeSubDomains",
    "Content-Security-Policy": contentSecurityPolicy(),
  } satisfies Record<string, string>;
}

export const BUCKET_ORIGIN = "https://upload.rcn.sh";

function baseDirectives(): string[] {
  return [
    "default-src 'self'",
    "base-uri 'self'",
    "form-action 'self'",
    "object-src 'none'",
    "font-src 'self'",
    `connect-src 'self' ${BUCKET_ORIGIN}`,
    `img-src 'self' data: https://*.scdn.co https://*.spotifycdn.com https://avatars.githubusercontent.com ${BUCKET_ORIGIN}`,
    `media-src 'self' ${BUCKET_ORIGIN}`,
    "upgrade-insecure-requests",
  ];
}

export const SCRIPT_SOURCES = [
  "'self'",
  "https://static.cloudflareinsights.com",
  "'wasm-unsafe-eval'",
];

function contentSecurityPolicy(): string {
  return [
    ...baseDirectives(),
    "frame-ancestors 'none'",
    `script-src ${SCRIPT_SOURCES.join(" ")} 'unsafe-inline'`,
    "style-src 'self' 'unsafe-inline'",
  ].join("; ");
}

export function completePolicy(existing: string): string {
  const present = new Set(
    existing
      .split(";")
      .map((directive) => directive.trim().split(/\s+/)[0]?.toLowerCase())
      .filter(Boolean),
  );
  const missing = [...baseDirectives(), "frame-ancestors 'none'"].filter(
    (directive) => !present.has(directive.split(" ")[0]),
  );
  const policy = existing.trim().replace(/;+$/, "");
  return missing.length ? [policy, ...missing].join("; ") : policy;
}

export function headersFile(): string {
  const rules = Object.entries(securityHeaders())
    .map(([name, value]) => `  ${name}: ${value}`)
    .join("\n");

  return `# Generated by scripts/generate-headers.ts — edit shared/security.ts.
#
# Statically served responses only; src/middleware.ts covers the rest. The
# Cloudflare adapter appends its own /_astro/* rule here at build time.

/*
${rules}
  Cache-Control: ${staticAssets}
`;
}
