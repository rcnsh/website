/**
 * The site's security headers, written once and served from two places:
 * public/_headers dresses prerendered pages Cloudflare serves without waking
 * the Worker, src/middleware.ts dresses everything else. Edit this file —
 * scripts/generate-headers.ts writes public/_headers out of it.
 *
 * Plain TypeScript, no Astro-isms: Vite, bare Node and astro.config.ts all
 * load it, and they do not understand the same things.
 */

export interface HeaderContext {
  /** In dev the cursor Worker is on its own port; in production `'self'` covers it. */
  dev?: boolean;
}

/** Both schemes: the socket, and the presence count beside it. */
const DEV_MULTIPLAYER = "ws://localhost:8788 http://localhost:8788";

export function securityHeaders({ dev = false }: HeaderContext = {}) {
  return {
    "X-Content-Type-Options": "nosniff",
    "X-Frame-Options": "DENY",
    "Referrer-Policy": "strict-origin-when-cross-origin",
    "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=()",
    "Strict-Transport-Security": "max-age=63072000; includeSubDomains",
    "Content-Security-Policy": contentSecurityPolicy(dev),
  } satisfies Record<string, string>;
}

/**
 * Everything the policy says that is not about scripts or styles. Shared
 * verbatim with the `<meta>` CSP Astro emits, since a browser enforces both
 * and a directive in only one has two answers.
 */
function baseDirectives(dev = false): string[] {
  return [
    "default-src 'self'",
    "base-uri 'self'",
    "form-action 'self'",
    "object-src 'none'",
    "font-src 'self'",
    // The cursor socket. Same origin, but `'self'` covering ws/wss is a CSP3
    // clarification some browsers were late to, so spell out the scheme.
    `connect-src 'self' wss://rcn.sh${dev ? ` ${DEV_MULTIPLAYER}` : ""}`,
    // Spotify spreads art across several scdn.co subdomains, hence wildcards.
    "img-src 'self' data: https://*.scdn.co https://*.spotifycdn.com https://avatars.githubusercontent.com https://upload.rcn.sh",
    "upgrade-insecure-requests",
  ];
}

/**
 * Sources for `script-src`, beyond the 'unsafe-inline' this header adds and
 * the hashes Astro adds to its own policy. Exported because astro.config.ts
 * feeds the same list to `security.csp.scriptDirective.resources`: a
 * prerendered page carries this header AND Astro's <meta>, a browser enforces
 * both, and a host named in only one is a host that is blocked. That is how
 * the beacon broke — the header allowed it and the meta did not.
 *
 * `'self'` is in the list because Astro's `resources` replaces its default
 * rather than extending it, so leaving it out would drop every same-origin
 * script from the meta policy.
 *
 * Cloudflare injects the Web Analytics beacon at the edge. The host and not
 * the file, because the injected URL carries a version after it, and a CSP
 * path without a trailing slash has to match exactly. It reports back to
 * /cdn-cgi/rum here, which connect-src 'self' already covers.
 */
export const SCRIPT_SOURCES = [
  "'self'",
  "https://static.cloudflareinsights.com",
];

/**
 * The policy. `script-src` and `style-src` carry 'unsafe-inline' because this
 * header is written ahead of time and cannot name Astro's inline scripts.
 *
 * Hashing them is `security.csp`, which is on — see astro.config.ts, which
 * explains at length why 'unsafe-inline' has to stay here anyway. In short:
 * a prerendered page is bound by this header and by Astro's <meta> at once,
 * the meta is the hash-locked one, and their intersection is what runs. Drop
 * 'unsafe-inline' from this header and that intersection admits no inline
 * script at all.
 */
function contentSecurityPolicy(dev: boolean): string {
  return [
    ...baseDirectives(dev),
    "frame-ancestors 'none'",
    `script-src ${SCRIPT_SOURCES.join(" ")} 'unsafe-inline'`,
    "style-src 'self' 'unsafe-inline'",
  ].join("; ");
}

/** The contents of public/_headers. Always the production set. */
export function headersFile(): string {
  const rules = Object.entries(securityHeaders())
    .map(([name, value]) => `  ${name}: ${value}`)
    .join("\n");

  return `# Generated by scripts/generate-headers.ts — edit shared/security.ts.
#
# Statically served responses only; src/middleware.ts covers everything the
# Worker renders. The Cloudflare adapter appends its own /_astro/* rule here
# at build time.

/*
${rules}
  Cache-Control: public, max-age=0, s-maxage=600, stale-while-revalidate=86400
`;
}
